export function getLessonContent({
  moduleTitle,
  title,
  description,
  content,
}: LessonContentInput): string {
  const key = `${moduleTitle}::${title}`;
  const override = lessonOverrides[key]?.content;
  if (!override) return content;

  const wordCount = content.trim().split(/\s+/).filter(Boolean).length;
  if (wordCount >= 40) return content;

  return override || `${description}\n\n${content}`;
}

export function getLessonEstimatedTime(
  moduleTitle: string,
  title: string,
  fallback: number
): number {
  const key = `${moduleTitle}::${title}`;
  return lessonOverrides[key]?.estimatedTime ?? fallback;
}
